#!/usr/bin/env node
// 从 protobuf descriptor 生成 ProtoBus(cline.*) 服务的运行时注册表。
// 输出 desktop/src/generated/protobus-registry.ts，供 Electron 主进程的
// gRPC 客户端桥接使用：把 webview 的 JSON 请求(fromJSON) 转成 ts-proto 实例，
// 调通 ProtoBus gRPC，再把响应(toJSON) 回传给 webview。
//
// 运行方式（在仓库根目录，确保 node_modules 含 @grpc/grpc-js 与 @grpc/proto-loader）：
//   node desktop/scripts/gen-protobus-registry.mjs
import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.resolve(__dirname, "..", "..")

// 依赖仓库根目录的 node_modules（@grpc/proto-loader、@grpc/grpc-js）
const { createRequire } = await import("module")
const require = createRequire(path.join(REPO_ROOT, "package.json"))
const grpc = require("@grpc/grpc-js")
const protoLoader = require("@grpc/proto-loader")

const DESCRIPTOR_CANDIDATES = [
	path.join(REPO_ROOT, "dist-standalone", "proto", "descriptor_set.pb"),
	path.join(REPO_ROOT, "proto", "descriptor_set.pb"),
]

const OUT_DIR = path.join(__dirname, "..", "src", "generated")
const OUT_FILE = path.join(OUT_DIR, "protobus-registry.ts")

function loadServices() {
	const descriptor = DESCRIPTOR_CANDIDATES.find((p) => fs.existsSync(p))
	if (!descriptor) {
		throw new Error(
			"未找到 protobuf descriptor。请先运行 `npm run protos` 生成 dist-standalone/proto/descriptor_set.pb。候选路径：\n  " +
				DESCRIPTOR_CANDIDATES.join("\n  "),
		)
	}
	const buf = fs.readFileSync(descriptor)
	const options = { longs: Number }
	const pkgDef = protoLoader.loadFileDescriptorSetFromBuffer(buf, options)
	const proto = grpc.loadPackageDefinition(pkgDef)
	return proto
}

function buildRegistry(proto) {
	// cline.* = ProtoBus（webview -> cline-core）
	const clineSvc = proto.cline ?? {}
	const registry = {}
	for (const [serviceName, def] of Object.entries(clineSvc)) {
		if (!def || !("service" in def)) continue
		registry[`cline.${serviceName}`] = {}
		for (const [rpcName, rpc] of Object.entries(def.service)) {
			const reqType = rpc.requestType?.type?.name ?? rpc.requestType?.name ?? "Empty"
			const respType = rpc.responseType?.type?.name ?? rpc.responseType?.name ?? "Empty"
			const streaming = Boolean(rpc.responseStream)
			registry[`cline.${serviceName}`][rpcName] = {
				req: `cline.${reqType}`,
				resp: `cline.${respType}`,
				streaming,
			}
		}
	}
	return registry
}

async function main() {
	const proto = loadServices()
	const registry = buildRegistry(proto)

	const serviceCount = Object.keys(registry).length
	const methodCount = Object.values(registry).reduce((n, s) => n + Object.keys(s).length, 0)

	const lines = []
	lines.push("// GENERATED CODE -- DO NOT EDIT!")
	lines.push(`// Generated by desktop/scripts/gen-protobus-registry.mjs (${serviceCount} services, ${methodCount} methods)`)
	lines.push(`// 引用 ${path.join("src", "generated", "grpc-js")} 中的 cline 命名空间消息类与 gRPC 客户端。`)
	lines.push("")
	lines.push(`export interface ProtoBusMethodDef {`)
	lines.push(`\treq: string`)
	lines.push(`\tresp: string`)
	lines.push(`\tstreaming: boolean`)
	lines.push(`}`)
	lines.push("")
	lines.push(`/** 键: "cline.<ServiceName>" -> 方法名 -> 请求/响应类型(FQN) 与是否服务端流式 */`)
	lines.push(`export const PROTOBUS_REGISTRY: Record<string, Record<string, ProtoBusMethodDef>> = `)
	lines.push(JSON.stringify(registry, null, 2).replace(/\n/g, "\n"))
	lines.push(`;`)
	lines.push("")

	fs.mkdirSync(OUT_DIR, { recursive: true })
	fs.writeFileSync(OUT_FILE, lines.join("\n"), "utf-8")
	console.log(`Wrote ${OUT_FILE}`)
	console.log(`  services=${serviceCount} methods=${methodCount}`)
}

main().catch((err) => {
	console.error(err)
	process.exit(1)
})
